import pytest

from app.modules.knowledge.safety import is_urgent

URGENT = [
    'Мальчик рассказал, что его обижают дома',
    'Девочка сказала, что отчим её бьёт',
    'Ребёнок сказал: «меня дома бьют ремнём»',
    'Подросток признался, что режет себя',
    'У девочки порезы на запястьях, что делать?',
    'Ребёнок сказал, что не хочет больше жить',
    'Мальчик говорит, что хочет умереть',
    'Девочка рассказала о сексуальном насилии',
    'Взрослый трогал его под одеждой',
    'Ему угрожают старшие ребята',
    'Мальчик сказал, что брат грозится избить его',
    'Говорит, что дома постоянно бьют',
    'Ребёнок рассказал про попытку суицида',
]

ORDINARY = [
    'Ребёнок попросил мой номер телефона. Что ответить?',
    'Можно ли взять ребят в музей в выходной?',
    'Что делать, если ребёнок не хочет рисовать?',
    'Ребёнок обиделся и не разговаривает',
    'Мальчик бьёт кулаком по столу, когда злится',
    'Девочка меня ударила, что делать?',
    'Можно ли насильно усаживать ребёнка за стол?',
    'Как объяснить ребёнку правила безопасности?',
    'Ребёнок не хочет уходить домой после занятия',
    'Он боится, что его не заберут домой',
    'Ребёнок трогает чужие вещи',
    'Как повесить рисунки на стену?',
]


@pytest.mark.parametrize('text', URGENT)
def test_child_safety_disclosures_are_urgent(text):
    assert is_urgent(text)


@pytest.mark.parametrize('text', ORDINARY)
def test_ordinary_questions_are_not_urgent(text):
    assert not is_urgent(text)
