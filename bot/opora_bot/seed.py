def seed() -> None:
    """Добавляет демо-события, если таблица пуста. Повторный запуск ничего не дублирует."""
    if db.one("SELECT COUNT(*) AS n FROM events")["n"]:
        return
    for e in EVENTS:
        row = {"end_date": None, "time": "", "end_time": "", "repeat": "none", "weekdays": "", "memo": "", **e}
        row["materials"] = json.dumps(row.pop("materials", []), ensure_ascii=False)
        cols = ", ".join(row)
        db.run(f"INSERT INTO events ({cols}) VALUES ({', '.join('?' * len(row))})", *row.values())
